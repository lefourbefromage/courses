export type Product = { canonical: string; category: CategoryId };

/** slug -> produit, pour le nom canonique comme pour chaque alias. */
export const PRODUCT_INDEX = new Map<string, Product>();
/** Tous les slugs canoniques, pour la correction orthographique floue. */
export const CANONICAL_SLUGS: { slug: string; product: Product }[] = [];

function slugForIndex(s: string): string {
  return s
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .replace(/œ/g, "oe")
    .replace(/æ/g, "ae")
    .toLowerCase()
    .replace(/['’]/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .split(" ")
    .map((w) => (w.length > 3 && /(s|x)$/.test(w) ? w.slice(0, -1) : w))
    .join(" ");
}

for (const [category, entries] of Object.entries(RAW) as [CategoryId, string[]][]) {
  for (const entry of entries) {
    const [canonical, aliasPart] = entry.split("|");
    const product: Product = { canonical, category };
    const canonicalSlug = slugForIndex(canonical);
    PRODUCT_INDEX.set(canonicalSlug, product);
    CANONICAL_SLUGS.push({ slug: canonicalSlug, product });
    if (aliasPart) {
      for (const alias of aliasPart.split(",")) {
        const aliasSlug = slugForIndex(alias);
        if (aliasSlug && !PRODUCT_INDEX.has(aliasSlug)) {
          PRODUCT_INDEX.set(aliasSlug, product);
        }
      }
    }
  }
}

export const PRODUCT_COUNT = CANONICAL_SLUGS.length;
